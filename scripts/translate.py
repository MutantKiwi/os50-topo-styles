def tr(s: str) -> str:
    if s in EXACT:
        return EXACT[s]
    out = s
    for pat, rep in TOKENS:
        out = re.sub(pat, rep, out)
    return out


def tr_layer(name: str) -> str:
    m = re.match(r"T(\d+)_DKM25_(.*)$", name)
    if m:
        return f"T{m.group(1)} {LAYERS.get(m.group(2), m.group(2))}"
    return LAYERS.get(name, name)


